import sympy as sp
from sympy import Matrix as M, Rational as R, eye, zeros, symbols

a, b = symbols("a b")


def swap(n, i, j):
    """I_ij：互换第 i、j 行（或列）。"""
    E = eye(n)
    E[i, i] = E[j, j] = 0
    E[i, j] = E[j, i] = 1
    return E


def scale(n, i, k):
    """I_i(k)。"""
    E = eye(n)
    E[i, i] = k
    return E


def Iij(n, i, j, k):
    """教材 I_ij(k)：k 位于 (j,i)；左乘 = 第 i 行的 k 倍加到第 j 行；右乘 = 第 j 列的 k 倍加到第 i 列。"""
    E = eye(n)
    E[j, i] = k
    return E


def IijT(n, i, j, k):
    """教材 I_ij^T(k)：k 位于 (i,j)；右乘 = 第 i 列的 k 倍加到第 j 列；左乘 = 第 j 行的 k 倍加到第 i 行。"""
    return Iij(n, i, j, k).T


def blk(rows):
    return sp.BlockMatrix(rows).as_explicit()


